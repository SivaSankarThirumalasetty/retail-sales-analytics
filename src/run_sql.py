"""
Load the processed star schema into SQLite and run every query in sql/business_queries.sql.
Results are written to reports/sql_results.md (and the DB to data/processed/retail.db).

Run: python src/run_sql.py
"""
from __future__ import annotations

import re
import sqlite3
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PROC = ROOT / "data" / "processed"


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    db = PROC / "retail.db"
    db.unlink(missing_ok=True)
    con = sqlite3.connect(db)
    for name in ["fact_order_lines", "dim_customers", "dim_products"]:
        pd.read_csv(PROC / f"{name}.csv.gz").to_sql(name, con, index=False)
    con.execute("CREATE INDEX ix_fact_cust ON fact_order_lines(customer_id)")
    con.execute("CREATE INDEX ix_fact_date ON fact_order_lines(order_date)")

    sql = (ROOT / "sql" / "business_queries.sql").read_text(encoding="utf-8")
    blocks = re.split(r"^-- name: ", sql, flags=re.M)[1:]
    out = ["# SQL results\n", "Generated by `src/run_sql.py` from `sql/business_queries.sql`.\n"]
    for b in blocks:
        name, body = b.split("\n", 1)
        title = next((l[3:] for l in body.splitlines() if l.startswith("-- Q")), name)
        df = pd.read_sql_query(body, con)
        table = df.to_markdown(index=False, floatfmt=",.1f")
        out.append(f"\n## {title}\n\n{table}\n")
        print(f"[ok] {name}: {len(df)} rows")
    (ROOT / "reports" / "sql_results.md").write_text("\n".join(out), encoding="utf-8")
    con.close()


if __name__ == "__main__":
    main()
